function normalizeText(value) {
  return String(value || '')
    .toLowerCase()
    .replace(/[‘’ʻ`´]/g, "'")
}

export function isOffTopic(message = '') {
  const text = normalizeText(message)
  if (!text.trim()) return false
  if (AGRO_HINTS.some((keyword) => text.includes(normalizeText(keyword)))) return false
  return OFF_TOPIC_HINTS.some((keyword) => text.includes(normalizeText(keyword)))
}
